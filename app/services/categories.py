def get_subcategory(category: str, note_or_text: str) -> Optional[str]:
    if not category or not note_or_text or category not in SUBCATEGORY_KEYWORDS:
        return None
    text_lower = note_or_text.lower()
    for subcat, kw_list in SUBCATEGORY_KEYWORDS[category].items():
        if any(kw in text_lower for kw in kw_list):
            return subcat
    return None
